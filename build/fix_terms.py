"""Приводит формулировки к терминологии проекта.

«на ходу» -> «с включённым двигателем», «на стоянке» -> «с выключенным».
Проверено по данным: в классе 1 зажигание включено в 89% событий при скорости
2.8 км/ч (машина стоит с работающим двигателем), в классе 2 датчик молчит
в 94% событий.
"""
import io
import re
import sys

FILES = [
    "C:/Users/79101/Downloads/Лаба_заправки/build/build_notebook.py",
    "C:/Users/79101/Downloads/Лаба_заправки/build/make_dataset.py",
    "C:/Users/79101/Downloads/Лаба_заправки/build/make_slide_figs.py",
    "C:/Users/79101/Downloads/Лаба_заправки/build/make_extra_figs.py",
    "C:/Users/79101/Downloads/Лаба_заправки/build/slides_content.py",
    "C:/Users/79101/Downloads/Лаба_заправки/README.md",
]

# длинные варианты идут первыми, чтобы не разрезать их короткими
PAIRS = [
    ("заправка при работающем двигателе", "заправка с включённым двигателем"),
    ("заправки при заглушенном двигателе", "заправки с выключенным двигателем"),
    ("заправок при заглушенном двигателе", "заправок с выключенным двигателем"),
    ("заправки при заглушенном", "заправки с выключенным двигателем"),
    ("пример заправки на стоянке", "пример заправки с выключенным двигателем"),
    ("пример заправки на ходу", "пример заправки с включённым двигателем"),
    ("заправка на ходу", "заправка с включённым двигателем"),
    ("заправку на ходу", "заправку с включённым двигателем"),
    ("заправки на ходу", "заправки с включённым двигателем"),
    ("заправок на ходу", "заправок с включённым двигателем"),
    ("заправкой на стоянке", "заправкой с выключенным двигателем"),
    ("заправка на стоянке", "заправка с выключенным двигателем"),
    ("заправки на стоянке", "заправки с выключенным двигателем"),
    ("заправок на стоянке", "заправок с выключенным двигателем"),
    ("для заправок на стоянке", "для заправок с выключенным двигателем"),
    # подписи на графиках — короткие формы, иначе не влезут
    ('"1 — на ходу"', '"1 — двигатель\\nвключён"'),
    ('"2 — на стоянке"', '"2 — двигатель\\nвыключен"'),
    ('["на стоянке", "на ходу"]', '["двигатель\\nвыключен", "двигатель\\nвключён"]'),
    ('"1 — заправка на ходу"', '"1 — двигатель включён"'),
    ('"2 — заправка на стоянке"', '"2 — двигатель выключен"'),
    ('"1 — заправка с включённым двигателем"', '"1 — двигатель включён"'),
    ('"2 — заправка с выключенным двигателем"', '"2 — двигатель выключен"'),
    ('"2 — на стоянке"', '"2 — двигатель выключен"'),
    # оставшиеся отдельные обороты
    ("Одно срабатывание на стоянке", "Одно срабатывание на пустом месте"),
    ("на ходу, 2 — на стоянке.", "с включённым двигателем, 2 — с выключенным."),
    ("интервалов — заправка на ходу", "интервалов — двигатель включён"),
    ("Заправка на ходу — это почти всегда",
     "Заправка с включённым двигателем — это почти всегда"),
]

total = 0
for path in FILES:
    s = io.open(path, encoding="utf-8").read()
    before = s
    n = 0
    for a, b in PAIRS:
        if a in s:
            n += s.count(a)
            s = s.replace(a, b)
    if s != before:
        io.open(path, "w", encoding="utf-8").write(s)
    left = re.findall(r"на ходу|на стоянке", s)
    total += n
    print(f"{path.split('/')[-1]:22s} замен {n:2d}"
          + (f", осталось: {set(left)}" if left else ""))

print(f"\nвсего замен: {total}")
