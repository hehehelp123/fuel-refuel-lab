def patch(path, blocks, label):
    s = io.open(path, encoding="utf-8").read()

    n_term = 0
    for pat, rep in TERM:
        s, k = re.subn(pat, rep, s)
        n_term += k

    for old, new in blocks:
        if old not in s:
            sys.exit(f"[{label}] не найден фрагмент:\n---\n{old[:200]}\n---")
        s = s.replace(old, new, 1)

    io.open(path, "w", encoding="utf-8").write(s)
    left = re.findall(r"\bбин\w*", s, flags=re.I)
    print(f"[{label}] замен термина: {n_term}, блоков переписано: {len(blocks)}, "
          f"осталось «бин*»: {left if left else 'нет'}")


